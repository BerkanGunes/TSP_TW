public class City {
    public final int id;
    public final int x;
    public final int y;
    public final int open;
    public final int close;

    public City(int id, int x, int y, int open, int close) {
        this.id = id;
        this.x = x;
        this.y = y;
        this.open = open;
        this.close = close;
    }
}
